export const TYPES = ['Hackathon', 'Bounty', 'Grant', 'Job', 'Course', 'Event', 'Program'] as const

export function statusOf(o: { deadline: string | null; status?: Status }, now = Date.now()): Status {
  if (o.status) return o.status
  if (!o.deadline) return 'Dates TBC'
  return new Date(o.deadline).getTime() < now ? 'Ended' : 'Open'
}

